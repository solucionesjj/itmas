using Itmas3.Application.SqlAudit.Abstractions;
using Itmas3.Domain.SqlAudit;
using Itmas3.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace Itmas3.Infrastructure.SqlAudit;

internal sealed class SqlInstanceRepository(AppDbContext db) : ISqlInstanceRepository
{
    public Task<SqlInstance?> GetAsync(Guid id, CancellationToken cancellationToken) =>
        db.SqlInstances.SingleOrDefaultAsync(instance => instance.Id == id, cancellationToken);

    public Task<SqlInstance?> FindAsync(Guid deviceId, SqlInstanceKey key, CancellationToken cancellationToken) =>
        db.SqlInstances.SingleOrDefaultAsync(
            instance => instance.DeviceId == deviceId
                && instance.Engine == key.Engine
                && instance.Host == key.Host
                && instance.Port == key.Port
                && instance.InstanceName == key.InstanceName,
            cancellationToken);

    public async Task<IReadOnlyList<Guid>> ListWithRiskCatalogBeforeAsync(int catalogVersion, CancellationToken cancellationToken) =>
        await db.SqlInstances.AsNoTracking()
            .Where(instance => instance.RiskCatalogVersion < catalogVersion)
            .Select(instance => instance.Id)
            .ToListAsync(cancellationToken);

    public void Add(SqlInstance instance) => db.SqlInstances.Add(instance);
}

internal sealed class SqlSnapshotReceiptRepository(AppDbContext db) : ISqlSnapshotReceiptRepository
{
    public Task<bool> ExistsAsync(Guid deviceId, Guid submissionId, CancellationToken cancellationToken) =>
        db.SqlSnapshotReceipts.AnyAsync(receipt => receipt.DeviceId == deviceId && receipt.SubmissionId == submissionId, cancellationToken);

    public void Add(SqlSnapshotReceipt receipt) => db.SqlSnapshotReceipts.Add(receipt);

    public Task<int> DeleteReceivedBeforeAsync(DateTimeOffset cutoff, CancellationToken cancellationToken) =>
        db.SqlSnapshotReceipts.Where(receipt => receipt.ReceivedAt < cutoff).ExecuteDeleteAsync(cancellationToken);
}

internal sealed class SqlAccountRepository(AppDbContext db) : ISqlAccountRepository
{
    public Task<SqlAccount?> GetAsync(Guid id, CancellationToken cancellationToken) =>
        db.SqlAccounts.SingleOrDefaultAsync(account => account.Id == id, cancellationToken);

    public async Task<IReadOnlyList<SqlAccount>> ListByInstanceAsync(Guid instanceId, CancellationToken cancellationToken) =>
        await db.SqlAccounts.Where(account => account.InstanceId == instanceId).ToListAsync(cancellationToken);

    public void AddRange(IEnumerable<SqlAccount> accounts) => db.SqlAccounts.AddRange(accounts);

    // Accounts still referenced by a remaining element (e.g. a role of another account) wait for that element.
    public Task<int> DeleteRemovedBeforeAsync(DateTimeOffset cutoff, CancellationToken cancellationToken) =>
        db.SqlAccounts
            .Where(account => account.RemovedAt < cutoff
                && !db.SqlAccessItems.Any(item => item.AccountId == account.Id || item.RoleAccountId == account.Id))
            .ExecuteDeleteAsync(cancellationToken);
}

/// <summary>
/// Set-based access to the elements (RNF-2): compact projections and <c>ExecuteUpdate</c> in chunks, so a snapshot with
/// hundreds of thousands of elements never tracks them all. Parameterised SQL generated by EF Core only.
/// </summary>
internal sealed class SqlAccessItemStore(AppDbContext db) : ISqlAccessItemStore
{
    private const int ChunkSize = 10_000;

    public Task<SqlAccessItem?> GetAsync(Guid id, CancellationToken cancellationToken) =>
        db.SqlAccessItems.SingleOrDefaultAsync(item => item.Id == id, cancellationToken);

    public async Task<IReadOnlyList<SqlAccessItemState>> ListStatesAsync(Guid instanceId, CancellationToken cancellationToken) =>
        await db.SqlAccessItems.AsNoTracking()
            .Where(item => item.InstanceId == instanceId)
            .Select(item => new SqlAccessItemState(
                item.Id,
                item.AccountId,
                item.IdentityHash,
                item.Kind,
                item.RoleAccountId,
                item.SecurableClass,
                item.DatabaseName,
                item.SchemaName,
                item.ObjectName,
                item.ObjectType,
                item.ColumnName,
                item.Permission,
                item.State,
                item.Grantor,
                item.Risk,
                item.RemovedAt))
            .ToListAsync(cancellationToken);

    public async Task InsertAsync(IReadOnlyCollection<SqlAccessItem> items, CancellationToken cancellationToken)
    {
        if (items.Count == 0)
        {
            return;
        }

        db.ChangeTracker.DetectChanges();
        await db.SaveChangesAsync(cancellationToken);
        await BulkInsert.CopyAsync(db, items, cancellationToken);
    }

    public Task MarkRemovedAsync(IReadOnlyCollection<Guid> ids, DateTimeOffset removedAt, CancellationToken cancellationToken) =>
        InChunksAsync(ids, (chunk, ct) => db.SqlAccessItems
            .Where(item => chunk.Contains(item.Id))
            .ExecuteUpdateAsync(setters => setters.SetProperty(item => item.RemovedAt, removedAt), ct), cancellationToken);

    public Task RestoreAsync(IReadOnlyCollection<Guid> ids, DateTimeOffset seenAt, CancellationToken cancellationToken) =>
        InChunksAsync(ids, (chunk, ct) => db.SqlAccessItems
            .Where(item => chunk.Contains(item.Id))
            .ExecuteUpdateAsync(setters => setters
                .SetProperty(item => item.RemovedAt, (DateTimeOffset?)null)
                .SetProperty(item => item.FirstSeenAt, seenAt)
                .SetProperty(item => item.LastSeenAt, seenAt)
                .SetProperty(item => item.ValidationStatus, SqlValidationStatus.Pending)
                .SetProperty(item => item.ValidatedByUserId, (Guid?)null)
                .SetProperty(item => item.ValidatedBy, (string?)null)
                .SetProperty(item => item.ValidatedAt, (DateTimeOffset?)null), ct), cancellationToken);

    public Task SetRiskAsync(IReadOnlyCollection<Guid> ids, RiskLevel risk, CancellationToken cancellationToken) =>
        InChunksAsync(ids, (chunk, ct) => db.SqlAccessItems
            .Where(item => chunk.Contains(item.Id))
            .ExecuteUpdateAsync(setters => setters.SetProperty(item => item.Risk, risk), ct), cancellationToken);

    public Task SetGrantorAsync(IReadOnlyCollection<Guid> ids, string? grantor, CancellationToken cancellationToken) =>
        InChunksAsync(ids, (chunk, ct) => db.SqlAccessItems
            .Where(item => chunk.Contains(item.Id))
            .ExecuteUpdateAsync(setters => setters.SetProperty(item => item.Grantor, grantor), ct), cancellationToken);

    public async Task TouchAsync(Guid instanceId, IReadOnlyList<SqlUnavailablePart> unavailable, DateTimeOffset seenAt, CancellationToken cancellationToken)
    {
        if (unavailable.Any(part => part.Section == SqlUnavailablePart.InstanceSection))
        {
            return;
        }

        var serverRead = SqlScopes.WasRead(unavailable, null);
        var unreadDatabases = unavailable
            .Where(part => part.Section.StartsWith(SqlUnavailablePart.DatabaseSectionPrefix, StringComparison.Ordinal))
            .Select(part => part.Section[SqlUnavailablePart.DatabaseSectionPrefix.Length..])
            .ToList();

        await db.SqlAccessItems
            .Where(item => item.InstanceId == instanceId && item.RemovedAt == null)
            .Where(item => item.DatabaseName == null ? serverRead : !unreadDatabases.Contains(item.DatabaseName))
            .ExecuteUpdateAsync(setters => setters.SetProperty(item => item.LastSeenAt, seenAt), cancellationToken);
    }

    public Task<int> DeleteRemovedBeforeAsync(DateTimeOffset cutoff, CancellationToken cancellationToken) =>
        db.SqlAccessItems.Where(item => item.RemovedAt < cutoff).ExecuteDeleteAsync(cancellationToken);

    private static async Task InChunksAsync(IReadOnlyCollection<Guid> ids, Func<List<Guid>, CancellationToken, Task<int>> update, CancellationToken cancellationToken)
    {
        foreach (var chunk in ids.Chunk(ChunkSize))
        {
            await update([.. chunk], cancellationToken);
        }
    }
}

internal sealed class SqlAccessChangeRepository(AppDbContext db) : ISqlAccessChangeRepository
{
    public void AddRange(IEnumerable<SqlAccessChange> changes) => db.SqlAccessChanges.AddRange(changes);

    public Task<int> DeleteDetectedBeforeAsync(DateTimeOffset cutoff, CancellationToken cancellationToken) =>
        db.SqlAccessChanges.Where(change => change.DetectedAt < cutoff).ExecuteDeleteAsync(cancellationToken);
}
